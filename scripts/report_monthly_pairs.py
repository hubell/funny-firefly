"""The geometry claim, month by month: ``reports/monthly_pairs.md``.

From the three held-out-pair folds ``scripts/fit_monthly_pairs.py`` refitted and
stored under ``data/processed/monthly_pairs/``, after its ``--check`` reproduced
``reports/baseline.md``'s figures from them. Nothing is refitted. Every
statistic is the claim's own, ``reports/baseline.md``'s *Held-out pairs*: the
fold-mean of per-fold RMSEs on each side, the difference in differences
between the two claim rungs, and the cluster bootstrap over pairs under its own
seed, restricted here to the rows of one month (or one airport, or both).

Usage::

    python scripts/report_monthly_pairs.py [--out PATH]
"""

from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

import numpy as np

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE))

import monthly as c  # noqa: E402
from monthly import rb  # noqa: E402
import fit_monthly_pairs as fp  # noqa: E402
from taxiout.models import LADDER_BY_KEY, SUBMISSION_KEY  # noqa: E402
from taxiout.validation import (  # noqa: E402
    BOOTSTRAP_DRAWS,
    BOOTSTRAP_LEVEL,
    PAIR_FOLDS,
    SEEN_FRACTION,
    cluster_bootstrap,
    difference_in_differences,
    fold_rmses,
    gap,
)

DEFAULT_OUT = c.REPO / "reports" / "monthly_pairs.md"
A, B = rb.CLAIM
SHIP = SUBMISSION_KEY


def reading(
    folds: dict, *, month: str | None = None, airport: str | None = None, d4: bool = False
) -> dict:
    """The claim's statistics over the rows of one month and/or airport."""
    keep = {}
    for f, data in folds.items():
        rows = data["rows"]
        m = np.ones(len(rows), bool)
        if month is not None:
            m &= rows["month"].to_numpy() == month
        if d4:
            m &= rows["y"].to_numpy(dtype=float) <= c.DAY_SHIFT_S
        keep[f] = m
    sums = fp.fold_sums(folds, airport=airport, keep=keep)
    out = {"folds": len(sums)}
    if not sums:
        return out
    held_n = [int(next(iter(f["held"].values())).n.sum()) for f in sums]
    seen_n = [int(next(iter(f["seen"].values())).n.sum()) for f in sums]
    out.update(
        {"held_n": held_n, "seen_n": seen_n, "held": sum(held_n), "seen": sum(seen_n)}
    )
    per = [fold_rmses(f) for f in sums]
    for k in fp.KEYS:
        out[f"seen_{k}"] = float(np.mean([p["seen"][k] for p in per]))
        out[f"held_{k}"] = float(np.mean([p["held"][k] for p in per]))
    if len(sums) == PAIR_FOLDS and min(seen_n) >= c.MIN_CELL_ROWS:
        out["did"] = cluster_bootstrap(sums, difference_in_differences(B, A))
        out["gap"] = cluster_bootstrap(sums, gap(SHIP))
    return out


def did_text(r: dict) -> str:
    if "did" not in r:
        return f"(held {r.get('held', 0):,} / seen {r.get('seen', 0):,} rows, {r['folds']} folds)"
    return str(r["did"])


def clears(r: dict) -> str:
    if "did" not in r:
        return ""
    return "yes" if (r["did"].low > 0 or r["did"].high < 0) else "no"


def build(folds: dict, check: dict) -> tuple[str, dict]:
    L: list[str] = []
    add = L.append
    log: dict = {"months": {}, "cells": {}}
    la, lb, ls = (LADDER_BY_KEY[k].label for k in (A, B, SHIP))
    add("# The geometry claim, month by month")
    add("")
    add(
        "Generated by `scripts/report_monthly_pairs.py` from the held-out-pair folds "
        "`scripts/fit_monthly_pairs.py` refitted "
        "and stored under `data/processed/monthly_pairs/`; nothing is refitted, every figure is computed there, and "
        "the generator refuses to write a movement identifier or a literal stand identifier. **It decides nothing.**"
    )
    add("")
    add("## What this is")
    add("")
    add(
        f"`reports/baseline.md`'s *Held-out pairs*: {PAIR_FOLDS} folds of `taxiout.validation.held_out_pair_splits`, "
        "each training on the whole year minus a third of every airport's (airport, stand, runway) pairs and scoring "
        f"those pairs in every month, beside a {SEEN_FRACTION:.0%} sample of rows whose pairs were seen and which "
        "were themselves out of the fit. So every month's rows are already in the design; what no file held was "
        "their per-row predictions, which `run_baselines.run` keeps in memory for these folds. `scripts/fit_monthly_pairs.py` "
        f"refitted the three folds by `run_baselines.run` itself for three rungs: `{la}` and `{lb}` "
        f"(the claim, `run_baselines.CLAIM`) and `{ls}` (the shipped rung, read for its gap alone), with "
        "`keep_residuals` off and `run_baselines.LADDER` pointed at the three rungs for the call and restored."
    )
    add("")
    add(
        f"**The fits are the ladder's**, checked before anything was read, from the stored files alone: {check['summary']}"
    )
    add("")
    add(
        "**The statistic is the claim's own definition, not a margin.** Within each fold, each rung's RMSE on the "
        "held-out pairs and on the seen sample; the figure is the mean over the three folds (the *fold-mean* "
        "`reports/baseline.md` defines), and the claim is the difference in differences, how much more the "
        "geometry block improves the held-out side than the seen side. Restricted to a month, the same "
        "statistic is computed over that month's rows on both sides. These are means of per-fold RMSEs by the "
        "claim's own definition, so `reports/monthly_ladder.md`'s rule that margins are pooled and never "
        "averaged does not apply to "
        f"them. The interval is the claim's: the {BOOTSTRAP_LEVEL:.0%} percentile interval of a cluster bootstrap "
        f"over pairs, {BOOTSTRAP_DRAWS:,} draws under `taxiout.validation.SEED`, resampling the pairs present in the "
        "restricted rows. Rows the record-quality term covers are out, as in `reports/baseline.md`. Beside each "
        "figure, the second reading over the rows whose recorded taxi-out is 4 h or less, a diagnostic. A cell whose "
        f"seen side holds under {c.MIN_CELL_ROWS} rows in any fold prints its counts only."
    )
    add("")
    add(
        "This is not a nested design: no fold was refitted per month, and a month's held-out pairs are the fold's, "
        "not pairs chosen within the month. A month here is a slice of the three folds' rows."
    )
    add("")

    # 1 ------------------------------------------------------------------
    add("## Per month of 2025")
    add("")
    rows = []
    keys = list(c.MONTHS) + ["year"]
    for k in keys:
        m = None if k == "year" else k
        r = reading(folds, month=m)
        r4 = reading(folds, month=m, d4=True)
        log["months"][k] = {
            "held": r.get("held"),
            "seen": r.get("seen"),
            "did": str(r.get("did")),
            "clears": clears(r),
            "did4": str(r4.get("did")),
            "clears4": clears(r4),
            "gap": str(r.get("gap")),
            "gap4": str(r4.get("gap")),
            **{
                f"{s}_{kk}": r.get(f"{s}_{kk}")
                for s in ("seen", "held")
                for kk in fp.KEYS
            },
            **{
                f"{s}4_{kk}": r4.get(f"{s}_{kk}")
                for s in ("seen", "held")
                for kk in fp.KEYS
            },
        }
        out4 = r.get("held", 0) + r.get("seen", 0) - r4.get("held", 0) - r4.get("seen", 0)
        label = "**the year**" if k == "year" else c.month_label(k)
        if "did" not in r:
            rows.append(
                [
                    label,
                    f"{r.get('held', 0):,}",
                    f"{r.get('seen', 0):,}",
                    "",
                    "",
                    did_text(r),
                    "",
                    "",
                ]
            )
            continue
        rows.append(
            [
                label,
                f"{r['held']:,}",
                f"{r['seen']:,}",
                f"{r['seen_' + A]:,.1f} / {r['held_' + A]:,.1f} [{r4['seen_' + A]:,.1f} / {r4['held_' + A]:,.1f}]",
                f"{r['seen_' + B]:,.1f} / {r['held_' + B]:,.1f} [{r4['seen_' + B]:,.1f} / {r4['held_' + B]:,.1f}]",
                f"**{r['did']}**" if k == "year" else str(r["did"]),
                clears(r),
                f"{r4.get('did', 'n/a')} ({out4:,} out)"
                if out4
                else f"{r4.get('did', 'n/a')}",
            ]
        )
    L += c.table(
        [
            "month",
            "held-out rows, 3 folds",
            "seen rows, 3 folds",
            f"`{la}`: seen / held out (s)",
            f"`{lb}`: seen / held out (s)",
            "the claim [95%]",
            "clears zero",
            "the claim over the rows of 4 h or less [95%] (diagnostic)",
        ],
        rows,
        "lrrrrrlr",
    )
    add("")
    add(
        "The bracketed seen / held-out figures beside each rung are the same fold-means over the rows of 4 h or less "
        "(diagnostic). The year's row is the figure `scripts/fit_monthly_pairs.py --check` reproduced against `reports/baseline.md`."
    )
    add("")

    # 2 ------------------------------------------------------------------
    add("## Per airport and month")
    add("")
    add(
        "The claim per airport, each month a row; the year's row is `reports/baseline.md`'s per-airport claim. "
        "Held-out and seen rows are summed over the three folds; *seen, least fold* is the smallest fold's seen "
        "side, which decides whether a cell prints."
    )
    summary_rows = []
    # the airports with departures; LTAI is in the airport table and has none
    airports = sorted(
        set(c.ICAOS)
        & set().union(*(set(d["rows"]["icao"].unique()) for d in folds.values()))
    )
    for ap in airports:
        add("")
        add(f"### {ap}")
        add("")
        rows = []
        clear_months, open_months, thin = [], [], []
        for k in keys:
            m = None if k == "year" else k
            r = reading(folds, month=m, airport=ap)
            r4 = reading(folds, month=m, airport=ap, d4=True)
            log["cells"][f"{ap} {k}"] = {
                "did": str(r.get("did")),
                "clears": clears(r),
                "held": r.get("held"),
                "seen": r.get("seen"),
                "did4": str(r4.get("did")),
            }
            label = "**the year**" if k == "year" else c.month_label(k)
            least = min(r.get("seen_n", [0])) if r.get("seen_n") else 0
            if "did" not in r:
                if k != "year":
                    thin.append(c.month_label(k))
                rows.append(
                    [
                        label,
                        f"{r.get('held', 0):,}",
                        f"{r.get('seen', 0):,}",
                        f"{least:,}",
                        "",
                        "",
                        did_text(r),
                        "",
                        "",
                    ]
                )
                continue
            if k != "year":
                (clear_months if clears(r) == "yes" else open_months).append(
                    c.month_label(k)
                )
            out4 = (
                r.get("held", 0)
                + r.get("seen", 0)
                - r4.get("held", 0)
                - r4.get("seen", 0)
            )

            def pair_text(key: str) -> str:
                t = f"{r['seen_' + key]:,.1f} / {r['held_' + key]:,.1f}"
                if out4 and f"seen_{key}" in r4:
                    t += f" [{r4['seen_' + key]:,.1f} / {r4['held_' + key]:,.1f}]"
                return t

            rows.append(
                [
                    label,
                    f"{r['held']:,}",
                    f"{r['seen']:,}",
                    f"{least:,}",
                    pair_text(A),
                    pair_text(B),
                    str(r["did"]),
                    clears(r),
                    (f"{r4.get('did', 'n/a')} ({out4:,} out)" if out4 else ""),
                ]
            )
        L += c.table(
            [
                "month",
                "held-out rows",
                "seen rows",
                "seen, least fold",
                f"`{la}`: seen / held out (s) [4 h or less]",
                f"`{lb}`: seen / held out (s) [4 h or less]",
                "the claim [95%]",
                "clears zero",
                "the claim over the rows of 4 h or less (diagnostic)",
            ],
            rows,
            "lrrrrrrlr",
        )
        summary_rows.append(
            [
                ap,
                f"{len(clear_months)}",
                ", ".join(open_months) or "none",
                ", ".join(thin) or "none",
            ]
        )
    add("")
    add(
        "Per airport, the months whose claim clears zero, those that do not, and those too thin to print:"
    )
    add("")
    L += c.table(
        ["ICAO", "months clear of zero", "months not clear", "months printed as counts"],
        summary_rows,
        "lrll",
    )
    add("")

    # 3 ------------------------------------------------------------------
    add("## The shipped rung's gap")
    add("")
    add(
        f"`{ls}`, held out minus seen, per month with its interval: how much worse the model that ships reads on a "
        "pair it has never seen. Context, not a claim; the same fold-mean statistic."
    )
    add("")
    rows = []
    for k in keys:
        lg = log["months"][k]
        label = "**the year**" if k == "year" else c.month_label(k)
        rows.append(
            [
                label,
                f"{lg['seen_' + SHIP]:,.1f} [{lg['seen4_' + SHIP]:,.1f}]",
                f"{lg['held_' + SHIP]:,.1f} [{lg['held4_' + SHIP]:,.1f}]",
                lg["gap"],
                lg["gap4"],
            ]
        )
    L += c.table(
        [
            "month",
            "seen (s) [4 h or less]",
            "held out (s) [4 h or less]",
            "gap [95%]",
            "gap over the rows of 4 h or less [95%] (diagnostic)",
        ],
        rows,
        "lrrrr",
    )
    add("")
    add(
        "The bracketed seen and held-out figures are over the rows of 4 h or less, a diagnostic."
    )
    add("")

    # 4 ------------------------------------------------------------------
    clear = [c.month_label(m) for m in c.MONTHS if log["months"][m]["clears"] == "yes"]
    not_clear = [
        c.month_label(m) for m in c.MONTHS if log["months"][m]["clears"] != "yes"
    ]
    clear4 = [m for m in c.MONTHS if log["months"][m]["clears4"] == "yes"]
    sentence = (
        f"**The claim clears zero in {len(clear)} of 12 months**"
        + (
            f"; it does not in {', '.join(not_clear)}."
            if not_clear
            else ", every month of 2025."
        )
        + f" Over the rows of 4 h or less, a diagnostic, it clears zero in {len(clear4)} of 12."
    )
    add("## In how many months the claim holds")
    add("")
    add(sentence)
    add("")
    log["sentence"] = sentence
    log["clear_months"] = clear
    log["not_clear_months"] = not_clear
    files = [fp.fold_path(f, k) for f in fp.fold_names() for k in fp.KEYS] + [
        fp.record_path(f) for f in fp.fold_names()
    ]
    L += c.inputs_footer(rb._inputs() + files + [fp.WORK / "check.json"])
    return "\n".join(L) + "\n", log


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--out", type=Path, default=DEFAULT_OUT)
    args = ap.parse_args(argv)
    before = c.fingerprint()
    chk = json.loads((fp.WORK / "check.json").read_text(encoding="utf-8"))
    if not chk["ok"]:
        raise SystemExit("fit_monthly_pairs.py --check did not pass; nothing is read")
    n_ok = sum(1 for x in chk["lines"] if x.startswith("[ok ]"))
    check = {
        "summary": f"{n_ok} of {len(chk['lines'])} comparisons held at the printed precision (against "
        "`reports/baseline.md`: the fold-mean seen and held-out figures, the gaps and the gaps "
        "per fold of the three rungs; the claim on seen pairs, "
        "on held-out pairs and as a difference with its interval; and the per-airport claim table row "
        "for row)."
    }
    folds = {f: fp.load_fold(f) for f in fp.fold_names()}
    text, _log = build(folds, check)
    dep = c.departures()
    ids = set()
    for d in folds.values():
        ids |= c.movement_ids(d["rows"]["mvt_id"])
    c.write(args.out, text, c.stands_of(dep), ids, before)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
