#!/usr/bin/env bash
# SPDX-License-Identifier: GPL-3.0-only
#
# One commit: the estimator docs/review_headroom.md line 8 promised.
#
# That line says that if any of the review's four candidate blocks were
# adopted, "the script becomes scripts/report_headroom.py and the numbers move
# to reports/". Section 7 of the same file records that all four were built and
# all four earned their place, so the condition was met on 8 September 2026 and
# the promise was not kept: until this commit, report_headroom.py appeared
# exactly once in the repository, in the sentence promising it, and the
# expected side of a firing gate could not be regenerated by anyone from the
# published repository.
#
# THE POINT OF THIS SCRIPT IS WHAT IT REFUSES. A change that both adds an
# instrument and makes a firing gate stop firing is indistinguishable from
# tuning the gate, whatever its commit message says. So three assertions below
# are the commit's own subject, each a grep that fails it:
#
#   1. HEADROOM_TRIGGER_S = 5.0 is unchanged in scripts/run_baselines.py.
#   2. EXPECTED_HEADROOM_S's four rows are unchanged, byte for byte.
#   3. reports/baseline.md is unchanged, byte for byte, against HEAD.
#
# The recomputed figures are printed BESIDE the quoted constant in
# reports/headroom.md, with their own date and method, and never in place of
# it. The leakage audit goes on reading the quoted figure and goes on firing.
# Refreshing the constant or restating the trigger is a second job and belongs
# in a separate change.
#
# Nothing under src/ or docs/ moves either: this adds a diagnostic and changes
# no feature, no rule and no review note. Two lines of README.md are the only
# edit outside this block's own files, and they correct a row that has been
# wrong since 13d60a9 gave reports/tails.md a second generator.
#
# Runs the tests, the lint and the licence gate first and stops if any fails,
# refuses a working tree holding anything but the six expected paths, and
# verifies the commit's own tree in a worktree before finishing. Nothing is
# pushed.

set -euo pipefail
cd "$(dirname "$0")/.."

say() { printf '\n== %s\n' "$1"; }

if [ ! -f LICENSE ] || [ ! -f pyproject.toml ]; then
    echo "Run this from the repository, not from somewhere else."
    exit 1
fi

# The other commit scripts here call python3 and ruff by their bare names. This
# one prefers the repository's own virtual environment when it is present,
# because the gate below is worth nothing if the interpreter running it has no
# pandas and skips two thirds of the tests.
PY="${PYTHON:-$([ -x .venv/bin/python ] && echo "$PWD/.venv/bin/python" || echo python3)}"
RUFF="$([ -x .venv/bin/ruff ] && echo "$PWD/.venv/bin/ruff" || echo ruff)"
# Absolute, because the worktree check at the end runs it from another directory.
case "$PY" in /*) ;; */*) PY="$PWD/$PY" ;; esac

GENERATOR="scripts/report_headroom.py"
REPORT="reports/headroom.md"
TESTS="tests/test_headroom.py"
LADDER="scripts/run_baselines.py"
BASELINE="reports/baseline.md"

PATHS="$GENERATOR $TESTS $REPORT Makefile README.md scripts/commit_headroom.sh"

for f in $PATHS; do
    if [ ! -f "$f" ]; then
        echo "missing $f -- nothing to commit"
        exit 1
    fi
done

say "the working tree holds these six paths and nothing else"
expected="$(printf '%s\n' $PATHS | sort)"
actual="$(git -c core.fileMode=false status --porcelain --untracked-files=all \
          | sed 's/^...//' | sort)"
if [ "$actual" != "$expected" ]; then
    echo "the tree is not what this script expects."
    diff <(echo "$expected") <(echo "$actual") || true
    exit 1
fi
echo "ok"

say "1/3 the trigger is unchanged"
# The constant this whole commit is written around. A commit that added the
# estimator and moved the allowance in one motion is the thing the analysis
# this block executes says must not happen.
if ! grep -qF "HEADROOM_TRIGGER_S = 5.0" "$LADDER"; then
    echo "$LADDER no longer carries \"HEADROOM_TRIGGER_S = 5.0\"."
    echo "This commit may not move the trigger. That is a separate change."
    exit 1
fi
echo "ok  HEADROOM_TRIGGER_S = 5.0"

say "2/3 EXPECTED_HEADROOM_S's four rows are unchanged, byte for byte"
# Not a diff read by eye and not a grep for four numbers: the block is cut out
# of HEAD's copy and out of the working copy by the same rule and the two byte
# strings are compared. A refreshed constant cannot pass this even if it kept
# the same shape.
work="$(mktemp -d)"
trap 'git worktree remove --force "$work/t" 2>/dev/null || true; rm -rf "$work"' EXIT
git show "HEAD:$LADDER" > "$work/ladder_head.py"
"$PY" - "$work/ladder_head.py" "$LADDER" <<'PY'
import sys
from pathlib import Path

OPEN = "EXPECTED_HEADROOM_S: dict[str, tuple[float, float]] = {"
KEYS = ("occupancy", "callsign", "destination", "plan-diffs")


def rows(path):
    lines = Path(path).read_text(encoding="utf-8").splitlines()
    start = [i for i, line in enumerate(lines) if line.strip() == OPEN]
    if len(start) != 1:
        raise SystemExit(f"{path}: {len(start)} copies of the constant's opening line")
    end = next(
        i for i in range(start[0] + 1, len(lines)) if lines[i].rstrip() == "}"
    )
    block = lines[start[0] + 1 : end]
    got = [line for line in block if line.lstrip().startswith('"')]
    if len(got) != len(KEYS):
        raise SystemExit(f"{path}: the constant has {len(got)} rows, not {len(KEYS)}")
    for key, line in zip(KEYS, got):
        if f'"{key}":' not in line:
            raise SystemExit(f"{path}: row for {key!r} is not where it was")
    return "\n".join(got)


head, working = rows(sys.argv[1]), rows(sys.argv[2])
if head != working:
    print("the four rows differ from HEAD's:", file=sys.stderr)
    for a, b in zip(head.splitlines(), working.splitlines()):
        if a != b:
            print(f"  HEAD:    {a.strip()}\n  working: {b.strip()}", file=sys.stderr)
    raise SystemExit(
        "This commit may not refresh EXPECTED_HEADROOM_S. That is a separate change."
    )
print("  " + "\n  ".join(line.strip() for line in working.splitlines()))
PY
echo "ok"

say "3/3 reports/baseline.md is unchanged, byte for byte"
# The file that carries the audit's verdict. If this commit moved it, the
# commit would be reporting a different verdict, which is exactly what it says
# it does not do.
if [ -n "$(git -c core.fileMode=false status --porcelain -- "$BASELINE")" ]; then
    echo "$BASELINE differs from HEAD. The audit's verdict is not this commit's to move."
    exit 1
fi
if ! git diff --quiet HEAD -- "$BASELINE"; then
    echo "$BASELINE differs from HEAD."
    exit 1
fi
echo "ok  the audit still reads what it read at HEAD"

say "the audit's verdict is still a firing one"
# Stated positively as well as negatively: the report this commit adds says the
# gate fires, and reports/baseline.md has to still say so too.
for pair in "$BASELINE:**The leakage audit, applied.**" \
            "$BASELINE:an overshoot of 7.301 s" \
            "$REPORT:it **fires**, at an overshoot of"; do
    f="${pair%%:*}"
    s="${pair#*:}"
    if ! grep -qF "$s" "$f"; then
        echo "$f does not carry \"$s\" -- the verdict this commit describes has moved"
        exit 1
    fi
done
echo "ok"

say "no feature, rule or review note moves"
for d in src/ docs/; do
    if [ -n "$(git -c core.fileMode=false status --porcelain -- "$d")" ]; then
        echo "$d differs from HEAD. This commit adds a diagnostic and changes no rule."
        exit 1
    fi
done
if [ -n "$(git -c core.fileMode=false status --porcelain -- "$LADDER")" ]; then
    echo "$LADDER differs from HEAD, and the ladder is not this commit's to change."
    exit 1
fi
echo "ok"

say "no figure in any other report moved"
others="$(git -c core.fileMode=false status --porcelain --untracked-files=all -- reports/ \
          | sed 's/^...//' | grep -v "^$REPORT$" || true)"
if [ -n "$others" ]; then
    echo "these reports also differ from HEAD, and this commit is not theirs to move:"
    echo "$others"
    exit 1
fi
echo "ok"

say "the report is newer than its generator and than the target that runs it"
for g in "$GENERATOR" Makefile; do
    if [ "$g" -nt "$REPORT" ]; then
        echo "$REPORT is older than $g -- rebuild it with 'make headroom'"
        exit 1
    fi
done
echo "ok"

say "the report carries what this commit is about"
check() {
    if ! grep -qF "$2" "$1"; then
        echo "$1 does not carry \"$2\" -- rebuild it with 'make headroom'"
        exit 1
    fi
}
# The capacity, named and written out, which is the substantive addition.
check "$REPORT" "## The capacity, named"
check "$REPORT" '`HEADROOM_BOOSTER_PARAMS`, in full:'
check "$REPORT" "capacity below is a reconstruction"
check "$REPORT" "### What the capacity is worth"
# The recomputed figures, beside the quoted ones rather than in place of them.
check "$REPORT" "## The recomputed headroom, beside the quoted figures"
check "$REPORT" "are not two measurements of one thing"
# The audit, unchanged, with its verdict repeated so this file does not mislead
# a reader who never opens baseline.md.
check "$REPORT" "**The audit is unchanged by this report.**"
check "$REPORT" "This report draws no conclusion about the trigger."
# The inputs, with the dates that make the figure identifiable at all.
check "$REPORT" "## The inputs, and why their dates are printed"
check "$REPORT" "december_encoding-for-stand.parquet"
# The generator names its capacity rather than importing the ladder's.
check "$GENERATOR" "HEADROOM_BOOSTER_PARAMS: dict[str, object] = {"
check "$GENERATOR" "HEADROOM_FOLDS = 5"
check "$GENERATOR" "HEADROOM_FOLD_SEED = 20260902"
# And the target exists, so the report is regenerable by the name the README
# gives it.
check Makefile "scripts/report_headroom.py"
check README.md "scripts/report_headroom.py"
# The row that has been wrong since reports/tails.md gained a second generator.
check README.md "scripts/pooled_tails.py"
echo "ok"

say "tests"
"$PY" -m pytest -q

say "lint"
"$RUFF" check .
"$RUFF" format --check .

say "licence gate"
"$PY" scripts/check_licence_hygiene.py

for p in ".cla""ude" "CLA""UDE.md"; do
    if [ -e "$p" ] && ! git check-ignore -q "$p"; then
        echo "$p exists and is not ignored -- fix .gitignore first"
        exit 1
    fi
done

BEFORE="$(git rev-parse HEAD)"

say "1/1 the estimator"
git add $PATHS
git commit -q -F - <<'MSG'
Bring in the headroom estimator the review promised, and move no threshold

docs/review_headroom.md line 8 says that if any of the review's four candidate
blocks were adopted, "the script becomes scripts/report_headroom.py and the
numbers move to reports/". Section 7 of that file records that all four were
built and all four earned their place, so the condition was met on 8 September.
The script never arrived. Until this commit report_headroom.py appeared exactly
once in the whole repository, in the sentence promising it, and the consequence
was that EXPECTED_HEADROOM_S, which gates the stand-occupancy leakage audit,
could not be regenerated by anyone from the published repository. That was true
whether or not the audit fired, and it is what this commit fixes.

The method is line 11 and nothing more: take the stored validation residuals of
the rung line 12 names, encoding-for-stand, join them back to the raw month,
build a candidate block from the feature registry's own columns for that block,
and fit a small booster on the residual with five-fold cross-validation grouped
by take-off day. The RMSE reduction is the headroom, read the way the queue
ceiling in reports/congestion.md is read. Forty small boosters and nothing of
the ladder, so it runs in three minutes.

The capacity is now a named constant, and that is the substantive addition.
Line 11 says "a small booster" and leaves it there, so every figure in section 2
is a figure about a capacity nobody wrote down, and an unnamed capacity is how
this quantity drifted out of comparability in the first place.
HEADROOM_BOOSTER_PARAMS writes every parameter out and says where each value
came from. It is not BOOSTER_PARAMS: the report measures the same block at three
capacities and the ladder's own cell reads a headroom of -2.45 s in December and
-8.77 s on the July three, because a cell fitted on 1.9 million training rows to
predict a taxi-out has capacity to spend inside its own folds when it is turned
loose on a frozen model's residual. A residual fit at that size would not
reproduce section 2's numbers even in principle.

The reconstruction is labelled as one. The original script is not in the tree
and its parameters are recorded nowhere in it, so the report states the rule
that chose the four capacity axes -- the smallest value on each axis of the grid
that was live when the review was written, read out of sweep_params.FIRST_SWEEP
rather than retyped -- and states that the rule was fixed after four candidate
cells had been read, so it is mechanical and stated but not pre-registered.

NO THRESHOLD, CONSTANT OR VERDICT MOVES. HEADROOM_TRIGGER_S is 5.0 s as it was,
EXPECTED_HEADROOM_S's four rows are unchanged byte for byte, HEADROOM_READINGS
gains nothing because no ladder ran, and reports/baseline.md is unchanged byte
for byte. This script's own gate asserts all four and refuses the commit
otherwise. The recomputed figures are printed beside the quoted constant with
their own date and method, never in place of it: a change that both added an
instrument and made a firing gate stop firing would be indistinguishable from
tuning the gate whatever its message said.

THE LEAKAGE AUDIT STILL FIRES. The audit reads the quoted constant, so it reads
what it read before: +17.60 s measured against +10.3 s estimated, an overshoot
of 7.301 s against the 5.000 s allowed. The recomputed figure for that cell is
+10.35 s, which is the closest of the eight keyed cells and leaves an overshoot
of 7.25 s and a ratio of 1.70. Section 7's own two readings of the same effect
are 1.69 and 2.26. What to do about a trigger specified in absolute seconds
against a quantity the same review documents as a floor is the second job, it is
decided on the evidence and disclosed as post-hoc if it changes anything, and it
is not this commit's.

Nothing under src/ or docs/ moves: this adds a diagnostic and changes no
feature, no rule and no review note. tests/test_headroom.py holds the four
properties that make the figure mean what the report says it means -- the folds
group by day and no day appears in two of them, a block of pure noise reads no
headroom, a column that reconstructs the residual reads the whole residual RMSE,
and the estimator refuses a column outside the block's registry entry -- and the
guard every published report carries.

Two lines of README.md are the only edit outside this block's own files. The
script table said scripts/report_tails.py produces reports/tails.md; since
13d60a9 that file is written by report_tails.py end to end and then by
pooled_tails.py --report, which writes one section into it, so the row was wrong
rather than merely incomplete. The row is corrected and pooled_tails.py is
added beside it.
MSG

say "the commit's own tree passes its own tests"
for sha in $(git rev-list --reverse "$BEFORE"..HEAD); do
    git worktree add --detach -q "$work/t" "$sha"
    if (cd "$work/t" && PYTHONPATH="$work/t/src" "$PY" -m pytest -q >/dev/null 2>&1); then
        printf '  ok   %s %s\n' "$(git log -1 --format=%h "$sha")" \
            "$(git log -1 --format=%s "$sha")"
    else
        printf '  FAIL %s %s\n' "$(git log -1 --format=%h "$sha")" \
            "$(git log -1 --format=%s "$sha")"
        git worktree remove --force "$work/t"
        exit 1
    fi
    git worktree remove --force "$work/t"
done

say "result"
git --no-pager log --oneline -5
echo
git status --short

say "nothing untracked that should be tracked"
git status --porcelain --untracked-files=all | grep '^??' || echo "clean"

echo
echo "Not pushed. Review with: git log -p -1"
